-- FindIt admin setup
-- Run this entire script in Supabase Dashboard > SQL Editor.
-- It preserves existing listings, claims, and user accounts.

create table if not exists public.admin_users (
    user_id uuid primary key references auth.users(id) on delete cascade,
    created_at timestamptz not null default now()
);

alter table public.admin_users enable row level security;

drop policy if exists "Admins can read their own admin role" on public.admin_users;
create policy "Admins can read their own admin role"
on public.admin_users
for select
to authenticated
using (auth.uid() = user_id);

create table if not exists public.admin_action_logs (
    id bigint generated by default as identity primary key,
    admin_user_id uuid references auth.users(id) on delete set null,
    action text not null,
    target_user_id uuid,
    target_listing_id bigint,
    reason text,
    details jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now()
);

alter table public.admin_action_logs enable row level security;

drop policy if exists "Admins can read admin action logs" on public.admin_action_logs;
create policy "Admins can read admin action logs"
on public.admin_action_logs
for select
to authenticated
using (
    exists (
        select 1
        from public.admin_users au
        where au.user_id = auth.uid()
    )
);

-- Promote the account created for FindIt administration.
-- This inserts only if the exact email exists in Supabase Auth.
insert into public.admin_users (user_id)
select id
from auth.users
where lower(email) = lower('finditadmin092@gmail.com')
on conflict (user_id) do nothing;

-- Confirm that exactly the intended admin account was found.
select au.user_id, u.email, au.created_at
from public.admin_users au
join auth.users u on u.id = au.user_id
where lower(u.email) = lower('finditadmin092@gmail.com');
